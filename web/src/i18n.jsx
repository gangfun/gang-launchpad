export const LANGS = [['en', 'EN'], ['zh-CN', '简'], ['zh-TW', '繁']]

function detect() {
  const saved = localStorage.getItem('gang.lang')
  if (saved && dict[saved]) return saved
  for (const l of navigator.languages || [navigator.language || 'en']) {
    const x = l.toLowerCase()
    if (x.startsWith('zh')) return /tw|hk|mo|hant/.test(x) ? 'zh-TW' : 'zh-CN'
    if (x.startsWith('en')) return 'en'
  }
  return 'en'
}

const Ctx = createContext({ lang: 'en', t: (k) => k, setLang: () => {} })
export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(detect)
  useEffect(() => { document.documentElement.lang = lang }, [lang])
  const value = useMemo(() => ({
    lang,
    t: (k, vars) => {
      let s = dict[lang][k] ?? dict.en[k] ?? k
      if (vars && typeof s === 'string') {
        for (const [key, val] of Object.entries(vars)) s = s.replaceAll(`{${key}}`, String(val))
      }
      return s
    },
    setLang: (l) => { localStorage.setItem('gang.lang', l); setLangState(l) },
  }), [lang])
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}
export const useT = () => useContext(Ctx)
/** Render a string or array of short lines, one per line. */
export const Lines = ({ k, className }) => { const { t } = useT(); const v = t(k); return <ul className={`lines ${className || ''}`}>{(Array.isArray(v) ? v : [v]).map((l, i) => <li key={i}>{l}</li>)}</ul> }
